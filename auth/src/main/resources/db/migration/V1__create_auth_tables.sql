-- Flyway creates the auth schema before this migration (spring.flyway.schemas=auth).
-- PostgreSQL stores TIMESTAMPTZ internally as an absolute instant.
CREATE TABLE auth.users (
    id UUID PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_auth_users_email_nonblank CHECK (length(btrim(email)) > 0),
    CONSTRAINT ck_auth_users_password_hash_nonblank CHECK (length(btrim(password_hash)) > 0)
);

-- Insensitive to letter case: one account per email even if case differs.
CREATE UNIQUE INDEX uq_auth_users_email_ci ON auth.users (lower(email));

CREATE TABLE auth.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL UNIQUE,
    CONSTRAINT ck_auth_roles_name CHECK (name IN ('ROLE_USER', 'ROLE_ADMIN'))
);

CREATE TABLE auth.user_roles (
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES auth.roles(id) ON DELETE RESTRICT,
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX idx_auth_user_roles_role ON auth.user_roles (role_id);
